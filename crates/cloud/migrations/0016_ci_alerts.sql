-- Email alerts of the CI Worker (crates/ci/src/alerts). Removing the
-- runner product took the old alerts with it, and nothing told anyone
-- when CI stopped launching jobs, ran out of GitHub requests or lost its
-- reconciler.

-- finished_at is when the last pass ended, history the last passes'
-- error counts as a JSON array, newest last, and digest_at when the
-- daily digest of firing alerts last went out. /healthz reads the first
-- two.
ALTER TABLE ci_reconciler
  ADD COLUMN finished_at bigint,
  ADD COLUMN history text,
  ADD COLUMN digest_at bigint;

-- One row per alert. state is what the last check found; sent is what
-- the last email said, NULL before the first. sending_until is when the
-- claim of the pass sending an email ends, NULL while nobody is.
CREATE TABLE ci_alerts (
  key text PRIMARY KEY,
  state text NOT NULL CHECK (state IN ('firing', 'resolved')),
  detail text NOT NULL,
  fired_at bigint NOT NULL,
  resolved_at bigint,
  sent text CHECK (sent IN ('firing', 'resolved')),
  sending_until bigint,
  updated_at bigint NOT NULL
);

-- Launches whose message ran out of retries and reached
-- hatchrun-ci-launches-dlq, once per message.
CREATE TABLE ci_failed_launches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id text NOT NULL UNIQUE,
  job_id bigint,
  job_name text,
  error text,
  attempts bigint,
  failed_at bigint NOT NULL
);
CREATE INDEX ci_failed_launches_age ON ci_failed_launches (failed_at);

-- Installations whose GitHub answers were rate limited or had little of
-- the hour's requests left.
CREATE TABLE ci_rate_limits (
  installation_id bigint PRIMARY KEY,
  remaining bigint,
  limited boolean NOT NULL,
  seen_at bigint NOT NULL
);
CREATE INDEX ci_rate_limits_seen ON ci_rate_limits (seen_at);
